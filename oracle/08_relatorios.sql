SET SERVEROUTPUT ON
SET VERIFY OFF

-- Correspondência entre registros Oracle e documentos MongoDB
SELECT 'ocorrencias' AS COLECAO, COUNT(*) AS DOCUMENTOS,
       LISTAGG(ID, ', ') WITHIN GROUP (ORDER BY ID) AS IDS
  FROM OCORRENCIA
UNION ALL
SELECT 'alertas', COUNT(*),
       LISTAGG(ID, ', ') WITHIN GROUP (ORDER BY ID)
  FROM ALERTA;

SELECT (SELECT COUNT(*) FROM TRIAGEM) AS TRIAGENS_EMBUTIDAS,
       (SELECT COUNT(*) FROM LAUDO) AS LAUDOS_EMBUTIDOS,
       (SELECT COUNT(*) FROM AUDITORIA_OCORRENCIA) AS HISTORICO_EMBUTIDO
  FROM DUAL;

-- Relatório 1: fila de análise do agrônomo (ocorrências por status)
SELECT O.ID,
       O.CULTURA,
       O.STATUS,
       O.SEVERIDADE,
       T.PRAGA_PROVAVEL,
       P.MUNICIPIO,
       P.UF,
       TO_CHAR(O.DATA_REGISTRO, 'YYYY-MM-DD HH24:MI') AS DATA_REGISTRO
  FROM OCORRENCIA O
  JOIN PROPRIEDADE P ON P.ID = O.PROPRIEDADE_ID
  LEFT JOIN TRIAGEM T ON T.OCORRENCIA_ID = O.ID
 WHERE O.STATUS IN ('TRIADA', 'EM_ANALISE')
 ORDER BY O.SEVERIDADE DESC NULLS LAST, O.DATA_REGISTRO;

-- Relatório 2: alertas ativos recebidos pela propriedade 12
SELECT A.ID,
       A.OCORRENCIA_ID,
       A.NIVEL,
       A.DISTANCIA_KM,
       A.LIDO,
       TO_CHAR(A.CRIADO_EM, 'YYYY-MM-DD HH24:MI') AS CRIADO_EM
  FROM ALERTA A
 WHERE A.PROPRIEDADE_ID = 12
   AND A.NIVEL <> 'ENCERRADO'
 ORDER BY A.CRIADO_EM DESC;

-- Relatório 3: ocorrências por praga, município e mês (agregação)
SELECT NVL(L.PRAGA_CONFIRMADA, T.PRAGA_PROVAVEL) AS PRAGA,
       P.MUNICIPIO,
       P.UF,
       TO_CHAR(O.DATA_REGISTRO, 'YYYY-MM') AS MES,
       COUNT(*) AS TOTAL,
       MAX(O.SEVERIDADE) AS MAIOR_SEVERIDADE,
       LISTAGG(O.ID, ', ') WITHIN GROUP (ORDER BY O.ID) AS OCORRENCIAS
  FROM OCORRENCIA O
  JOIN PROPRIEDADE P ON P.ID = O.PROPRIEDADE_ID
  LEFT JOIN TRIAGEM T ON T.OCORRENCIA_ID = O.ID
  LEFT JOIN LAUDO L ON L.OCORRENCIA_ID = O.ID AND L.DECISAO = 'CONFIRMADA'
 WHERE O.STATUS <> 'DESCARTADA'
   AND NVL(L.PRAGA_CONFIRMADA, T.PRAGA_PROVAVEL) IS NOT NULL
 GROUP BY NVL(L.PRAGA_CONFIRMADA, T.PRAGA_PROVAVEL), P.MUNICIPIO, P.UF, TO_CHAR(O.DATA_REGISTRO, 'YYYY-MM')
 ORDER BY TOTAL DESC, PRAGA, P.MUNICIPIO, MES;
