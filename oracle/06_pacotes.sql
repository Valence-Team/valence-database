-- Pacote de alertas: especificação
CREATE OR REPLACE PACKAGE PKG_ALERTA IS
    C_RAIO_PADRAO_KM CONSTANT NUMBER := 10;

    E_STATUS_SEM_ALERTA EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_STATUS_SEM_ALERTA, -20041);

    FUNCTION FN_DISTANCIA_KM (
        P_LAT_ORIGEM    IN NUMBER,
        P_LON_ORIGEM    IN NUMBER,
        P_LAT_DESTINO   IN NUMBER,
        P_LON_DESTINO   IN NUMBER
    ) RETURN NUMBER;

    PROCEDURE PRC_EMITIR_ALERTAS_RAIO (
        P_OCORRENCIA_ID IN  OCORRENCIA.ID%TYPE,
        P_RAIO_KM       IN  NUMBER DEFAULT C_RAIO_PADRAO_KM,
        P_QTD_ALERTAS   OUT NUMBER
    );

    PROCEDURE PRC_ATUALIZAR_NIVEL (
        P_OCORRENCIA_ID IN  OCORRENCIA.ID%TYPE,
        P_NIVEL         IN  ALERTA.NIVEL%TYPE,
        P_QTD_ALTERADOS OUT NUMBER
    );
END PKG_ALERTA;
/

-- Pacote de alertas: corpo
CREATE OR REPLACE PACKAGE BODY PKG_ALERTA IS
    C_RAIO_TERRA_KM CONSTANT NUMBER := 6371;
    C_GRAU_EM_RAD   CONSTANT NUMBER := ACOS(-1) / 180;

    FUNCTION FN_DISTANCIA_KM (
        P_LAT_ORIGEM    IN NUMBER,
        P_LON_ORIGEM    IN NUMBER,
        P_LAT_DESTINO   IN NUMBER,
        P_LON_DESTINO   IN NUMBER
    ) RETURN NUMBER
    IS
        V_DIF_LAT   NUMBER;
        V_DIF_LON   NUMBER;
        V_A         NUMBER;
        V_DISTANCIA NUMBER;
        E_COORDENADA_INVALIDA EXCEPTION;
    BEGIN
        IF P_LAT_ORIGEM IS NULL OR P_LON_ORIGEM IS NULL
           OR P_LAT_DESTINO IS NULL OR P_LON_DESTINO IS NULL THEN
            RAISE E_COORDENADA_INVALIDA;
        END IF;

        IF ABS(P_LAT_ORIGEM) > 90 OR ABS(P_LAT_DESTINO) > 90
           OR ABS(P_LON_ORIGEM) > 180 OR ABS(P_LON_DESTINO) > 180 THEN
            RAISE E_COORDENADA_INVALIDA;
        END IF;

        V_DIF_LAT := (P_LAT_DESTINO - P_LAT_ORIGEM) * C_GRAU_EM_RAD;
        V_DIF_LON := (P_LON_DESTINO - P_LON_ORIGEM) * C_GRAU_EM_RAD;

        V_A := POWER(SIN(V_DIF_LAT / 2), 2)
             + COS(P_LAT_ORIGEM * C_GRAU_EM_RAD) * COS(P_LAT_DESTINO * C_GRAU_EM_RAD)
             * POWER(SIN(V_DIF_LON / 2), 2);

        V_DISTANCIA := 2 * C_RAIO_TERRA_KM * ASIN(LEAST(1, SQRT(V_A)));

        RETURN ROUND(V_DISTANCIA, 3);
    EXCEPTION
        WHEN E_COORDENADA_INVALIDA THEN
            RAISE_APPLICATION_ERROR(-20010, 'Coordenadas inválidas: latitude deve estar entre -90 e 90 '
                                    || 'e longitude entre -180 e 180, todas preenchidas.');
    END FN_DISTANCIA_KM;

    PROCEDURE PRC_EMITIR_ALERTAS_RAIO (
        P_OCORRENCIA_ID IN  OCORRENCIA.ID%TYPE,
        P_RAIO_KM       IN  NUMBER DEFAULT C_RAIO_PADRAO_KM,
        P_QTD_ALERTAS   OUT NUMBER
    )
    IS
        CURSOR C_VIZINHAS (P_CULTURA_ALVO VARCHAR2, P_PROPRIEDADE_ORIGEM NUMBER) IS
            SELECT P.ID, P.NOME, P.LATITUDE, P.LONGITUDE
              FROM PROPRIEDADE P
              JOIN PROPRIEDADE_CULTURA PC ON PC.PROPRIEDADE_ID = P.ID
             WHERE PC.CULTURA = P_CULTURA_ALVO
               AND P.ID <> P_PROPRIEDADE_ORIGEM
             ORDER BY P.ID;

        V_STATUS        OCORRENCIA.STATUS%TYPE;
        V_CULTURA       OCORRENCIA.CULTURA%TYPE;
        V_ORIGEM        OCORRENCIA.PROPRIEDADE_ID%TYPE;
        V_LAT_ORIGEM    PROPRIEDADE.LATITUDE%TYPE;
        V_LON_ORIGEM    PROPRIEDADE.LONGITUDE%TYPE;
        V_NIVEL         ALERTA.NIVEL%TYPE;
        V_DISTANCIA     NUMBER;
        V_JA_ALERTADA   NUMBER;

        E_RAIO_INVALIDO             EXCEPTION;
        E_OCORRENCIA_NAO_ENCONTRADA EXCEPTION;
    BEGIN
        P_QTD_ALERTAS := 0;

        IF P_RAIO_KM IS NULL OR P_RAIO_KM <= 0 THEN
            RAISE E_RAIO_INVALIDO;
        END IF;

        BEGIN
            SELECT O.STATUS, O.CULTURA, O.PROPRIEDADE_ID, P.LATITUDE, P.LONGITUDE
              INTO V_STATUS, V_CULTURA, V_ORIGEM, V_LAT_ORIGEM, V_LON_ORIGEM
              FROM OCORRENCIA O
              JOIN PROPRIEDADE P ON P.ID = O.PROPRIEDADE_ID
             WHERE O.ID = P_OCORRENCIA_ID;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE E_OCORRENCIA_NAO_ENCONTRADA;
        END;

        IF V_STATUS NOT IN ('TRIADA', 'EM_ANALISE', 'CONFIRMADA') THEN
            RAISE E_STATUS_SEM_ALERTA;
        END IF;

        IF V_STATUS = 'CONFIRMADA' THEN
            V_NIVEL := 'CONFIRMADO';
        ELSE
            V_NIVEL := 'SUSPEITA';
        END IF;

        DBMS_OUTPUT.PUT_LINE('Ocorrência ' || P_OCORRENCIA_ID || ' (' || V_CULTURA || ', ' || V_STATUS
                             || '), raio de ' || P_RAIO_KM || ' km:');

        FOR V_VIZINHA IN C_VIZINHAS(V_CULTURA, V_ORIGEM) LOOP
            V_DISTANCIA := FN_DISTANCIA_KM(V_LAT_ORIGEM, V_LON_ORIGEM,
                                           V_VIZINHA.LATITUDE, V_VIZINHA.LONGITUDE);

            IF V_DISTANCIA > P_RAIO_KM THEN
                DBMS_OUTPUT.PUT_LINE('  Propriedade ' || V_VIZINHA.ID || ' ' || V_VIZINHA.NOME || ': '
                                     || TO_CHAR(V_DISTANCIA, 'FM99990D0') || ' km, fora do raio');
            ELSE
                SELECT COUNT(*)
                  INTO V_JA_ALERTADA
                  FROM ALERTA
                 WHERE OCORRENCIA_ID = P_OCORRENCIA_ID
                   AND PROPRIEDADE_ID = V_VIZINHA.ID;

                IF V_JA_ALERTADA > 0 THEN
                    DBMS_OUTPUT.PUT_LINE('  Propriedade ' || V_VIZINHA.ID || ' ' || V_VIZINHA.NOME || ': '
                                         || TO_CHAR(V_DISTANCIA, 'FM99990D0') || ' km, já tinha alerta');
                ELSE
                    INSERT INTO ALERTA
                        (ID, OCORRENCIA_ID, PROPRIEDADE_ID, NIVEL, DISTANCIA_KM, LIDO, CRIADO_EM)
                    VALUES
                        (SEQ_VALENCE_ALERTA.NEXTVAL, P_OCORRENCIA_ID, V_VIZINHA.ID, V_NIVEL,
                         GREATEST(1, ROUND(V_DISTANCIA)), 'N', SYSTIMESTAMP);

                    P_QTD_ALERTAS := P_QTD_ALERTAS + 1;
                    DBMS_OUTPUT.PUT_LINE('  Propriedade ' || V_VIZINHA.ID || ' ' || V_VIZINHA.NOME || ': '
                                         || TO_CHAR(V_DISTANCIA, 'FM99990D0') || ' km, alerta '
                                         || V_NIVEL || ' criado');
                END IF;
            END IF;
        END LOOP;

        DBMS_OUTPUT.PUT_LINE('Alertas criados: ' || P_QTD_ALERTAS);
    EXCEPTION
        WHEN E_RAIO_INVALIDO THEN
            RAISE_APPLICATION_ERROR(-20042, 'O raio deve ser maior que zero.');
        WHEN E_OCORRENCIA_NAO_ENCONTRADA THEN
            RAISE_APPLICATION_ERROR(-20040, 'Ocorrência ' || P_OCORRENCIA_ID || ' não encontrada.');
        WHEN E_STATUS_SEM_ALERTA THEN
            RAISE_APPLICATION_ERROR(-20041, 'Alertas só são emitidos para ocorrências triadas, em análise '
                                    || 'ou confirmadas. Status atual: ' || V_STATUS || '.');
    END PRC_EMITIR_ALERTAS_RAIO;

    PROCEDURE PRC_ATUALIZAR_NIVEL (
        P_OCORRENCIA_ID IN  OCORRENCIA.ID%TYPE,
        P_NIVEL         IN  ALERTA.NIVEL%TYPE,
        P_QTD_ALTERADOS OUT NUMBER
    )
    IS
        V_NIVEL         VARCHAR2(30) := UPPER(TRIM(P_NIVEL));
        E_NIVEL_INVALIDO EXCEPTION;
    BEGIN
        IF V_NIVEL IS NULL OR V_NIVEL NOT IN ('SUSPEITA', 'CONFIRMADO', 'ENCERRADO') THEN
            RAISE E_NIVEL_INVALIDO;
        END IF;

        UPDATE ALERTA
           SET NIVEL = V_NIVEL,
               LIDO = 'N'
         WHERE OCORRENCIA_ID = P_OCORRENCIA_ID
           AND NIVEL <> V_NIVEL;

        P_QTD_ALTERADOS := SQL%ROWCOUNT;
        DBMS_OUTPUT.PUT_LINE('Alertas da ocorrência ' || P_OCORRENCIA_ID || ' alterados para '
                             || V_NIVEL || ': ' || P_QTD_ALTERADOS);
    EXCEPTION
        WHEN E_NIVEL_INVALIDO THEN
            RAISE_APPLICATION_ERROR(-20043, 'Nível de alerta inválido: use SUSPEITA, CONFIRMADO ou ENCERRADO.');
    END PRC_ATUALIZAR_NIVEL;
END PKG_ALERTA;
