-- Pacote de ocorrências: corpo
CREATE OR REPLACE PACKAGE BODY PKG_OCORRENCIA IS

    FUNCTION FN_TRANSICAO_PERMITIDA (
        P_STATUS_ATUAL  IN VARCHAR2,
        P_STATUS_NOVO   IN VARCHAR2
    ) RETURN BOOLEAN
    IS
    BEGIN
        RETURN (P_STATUS_ATUAL = 'RECEBIDA' AND P_STATUS_NOVO IN ('TRIADA', 'EM_ANALISE'))
            OR (P_STATUS_ATUAL = 'TRIADA' AND P_STATUS_NOVO = 'EM_ANALISE')
            OR (P_STATUS_ATUAL = 'EM_ANALISE' AND P_STATUS_NOVO IN ('CONFIRMADA', 'DESCARTADA'));
    EXCEPTION
        WHEN OTHERS THEN
            RETURN FALSE;
    END FN_TRANSICAO_PERMITIDA;

    FUNCTION FN_NIVEL_RISCO (
        P_SEVERIDADE    IN NUMBER,
        P_MUNICIPIO     IN VARCHAR2,
        P_UF            IN VARCHAR2
    ) RETURN VARCHAR2
    IS
        V_OCORRENCIAS_ATIVAS NUMBER;
        V_NIVEL              VARCHAR2(7);
        E_SEVERIDADE_INVALIDA EXCEPTION;
        E_LOCAL_INVALIDO      EXCEPTION;
    BEGIN
        IF P_SEVERIDADE IS NULL OR P_SEVERIDADE NOT BETWEEN 1 AND 5
           OR P_SEVERIDADE <> TRUNC(P_SEVERIDADE) THEN
            RAISE E_SEVERIDADE_INVALIDA;
        END IF;

        IF TRIM(P_MUNICIPIO) IS NULL OR TRIM(P_UF) IS NULL THEN
            RAISE E_LOCAL_INVALIDO;
        END IF;

        SELECT COUNT(*)
          INTO V_OCORRENCIAS_ATIVAS
          FROM OCORRENCIA O
          JOIN PROPRIEDADE P ON P.ID = O.PROPRIEDADE_ID
         WHERE UPPER(P.MUNICIPIO) = UPPER(TRIM(P_MUNICIPIO))
           AND P.UF = UPPER(TRIM(P_UF))
           AND O.STATUS IN ('TRIADA', 'EM_ANALISE', 'CONFIRMADA');

        IF P_SEVERIDADE = 5 OR (P_SEVERIDADE = 4 AND V_OCORRENCIAS_ATIVAS >= 3) THEN
            V_NIVEL := 'CRITICO';
        ELSIF P_SEVERIDADE = 4 OR (P_SEVERIDADE = 3 AND V_OCORRENCIAS_ATIVAS >= 2) THEN
            V_NIVEL := 'ALTO';
        ELSIF P_SEVERIDADE = 3 OR (P_SEVERIDADE = 2 AND V_OCORRENCIAS_ATIVAS >= 2) THEN
            V_NIVEL := 'MEDIO';
        ELSE
            V_NIVEL := 'BAIXO';
        END IF;

        RETURN V_NIVEL;
    EXCEPTION
        WHEN E_SEVERIDADE_INVALIDA THEN
            RAISE_APPLICATION_ERROR(-20020, 'Severidade inválida: o valor deve ser inteiro de 1 a 5.');
        WHEN E_LOCAL_INVALIDO THEN
            RAISE_APPLICATION_ERROR(-20021, 'Município e UF são obrigatórios para calcular o risco.');
    END FN_NIVEL_RISCO;

    PROCEDURE PRC_REGISTRAR_OCORRENCIA (
        P_USUARIO_ID        IN  OCORRENCIA.USUARIO_ID%TYPE,
        P_PROPRIEDADE_ID    IN  OCORRENCIA.PROPRIEDADE_ID%TYPE,
        P_CULTURA           IN  OCORRENCIA.CULTURA%TYPE,
        P_DESCRICAO         IN  OCORRENCIA.DESCRICAO%TYPE,
        P_IDEMPOTENCY_KEY   IN  OCORRENCIA.IDEMPOTENCY_KEY%TYPE,
        P_OCORRENCIA_ID     OUT OCORRENCIA.ID%TYPE
    )
    IS
        V_PAPEL             USUARIO.PAPEL%TYPE;
        V_DONO              PROPRIEDADE.USUARIO_ID%TYPE;
        V_CULTIVA           NUMBER;
        V_CULTURA           VARCHAR2(50)    := UPPER(TRIM(P_CULTURA));
        V_DESCRICAO         VARCHAR2(32767) := TRIM(P_DESCRICAO);
        V_CHAVE             VARCHAR2(100)   := LOWER(TRIM(P_IDEMPOTENCY_KEY));
        V_EXISTENTE_ID      OCORRENCIA.ID%TYPE;
        V_EXISTENTE_PROP    OCORRENCIA.PROPRIEDADE_ID%TYPE;
        V_EXISTENTE_CULTURA OCORRENCIA.CULTURA%TYPE;
        V_EXISTENTE_DESC    OCORRENCIA.DESCRICAO%TYPE;

        E_USUARIO_NAO_ENCONTRADO     EXCEPTION;
        E_USUARIO_NAO_PRODUTOR       EXCEPTION;
        E_PROPRIEDADE_NAO_ENCONTRADA EXCEPTION;
        E_CULTURA_NAO_CULTIVADA      EXCEPTION;
        E_DESCRICAO_INVALIDA         EXCEPTION;
        E_CHAVE_INVALIDA             EXCEPTION;
        E_CHAVE_REUTILIZADA          EXCEPTION;
    BEGIN
        BEGIN
            SELECT PAPEL INTO V_PAPEL FROM USUARIO WHERE ID = P_USUARIO_ID;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE E_USUARIO_NAO_ENCONTRADO;
        END;

        IF V_PAPEL <> 'PRODUTOR' THEN
            RAISE E_USUARIO_NAO_PRODUTOR;
        END IF;

        BEGIN
            SELECT USUARIO_ID INTO V_DONO FROM PROPRIEDADE WHERE ID = P_PROPRIEDADE_ID;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE E_PROPRIEDADE_NAO_ENCONTRADA;
        END;

        IF V_DONO <> P_USUARIO_ID THEN
            RAISE E_PROPRIEDADE_NAO_ENCONTRADA;
        END IF;

        SELECT COUNT(*)
          INTO V_CULTIVA
          FROM PROPRIEDADE_CULTURA
         WHERE PROPRIEDADE_ID = P_PROPRIEDADE_ID
           AND CULTURA = V_CULTURA;

        IF V_CULTIVA = 0 THEN
            RAISE E_CULTURA_NAO_CULTIVADA;
        END IF;

        IF V_DESCRICAO IS NULL OR LENGTH(V_DESCRICAO) NOT BETWEEN 10 AND 1000 THEN
            RAISE E_DESCRICAO_INVALIDA;
        END IF;

        IF V_CHAVE IS NULL
           OR NOT REGEXP_LIKE(V_CHAVE, '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$') THEN
            RAISE E_CHAVE_INVALIDA;
        END IF;

        BEGIN
            SELECT ID, PROPRIEDADE_ID, CULTURA, DESCRICAO
              INTO V_EXISTENTE_ID, V_EXISTENTE_PROP, V_EXISTENTE_CULTURA, V_EXISTENTE_DESC
              FROM OCORRENCIA
             WHERE USUARIO_ID = P_USUARIO_ID
               AND IDEMPOTENCY_KEY = V_CHAVE;

            IF V_EXISTENTE_PROP = P_PROPRIEDADE_ID
               AND V_EXISTENTE_CULTURA = V_CULTURA
               AND V_EXISTENTE_DESC = V_DESCRICAO THEN
                P_OCORRENCIA_ID := V_EXISTENTE_ID;
                DBMS_OUTPUT.PUT_LINE('Requisição repetida: devolvida a ocorrência ' || V_EXISTENTE_ID
                                     || ', sem nova gravação.');
                RETURN;
            END IF;

            RAISE E_CHAVE_REUTILIZADA;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                NULL;
        END;

        INSERT INTO OCORRENCIA
            (ID, PROPRIEDADE_ID, USUARIO_ID, CULTURA, DESCRICAO, STATUS, SEVERIDADE,
             IDEMPOTENCY_KEY, DATA_REGISTRO, ATUALIZADO_EM)
        VALUES
            (SEQ_VALENCE_OCORRENCIA.NEXTVAL, P_PROPRIEDADE_ID, P_USUARIO_ID, V_CULTURA, V_DESCRICAO,
             'RECEBIDA', NULL, V_CHAVE, SYSTIMESTAMP, SYSTIMESTAMP)
        RETURNING ID INTO P_OCORRENCIA_ID;

        DBMS_OUTPUT.PUT_LINE('Ocorrência ' || P_OCORRENCIA_ID || ' registrada com status RECEBIDA.');
    EXCEPTION
        WHEN E_USUARIO_NAO_ENCONTRADO THEN
            RAISE_APPLICATION_ERROR(-20030, 'Usuário ' || P_USUARIO_ID || ' não encontrado.');
        WHEN E_USUARIO_NAO_PRODUTOR THEN
            RAISE_APPLICATION_ERROR(-20031, 'Somente produtores registram ocorrências. Papel do usuário: '
                                    || V_PAPEL || '.');
        WHEN E_PROPRIEDADE_NAO_ENCONTRADA THEN
            RAISE_APPLICATION_ERROR(-20032, 'Propriedade ' || P_PROPRIEDADE_ID
                                    || ' não encontrada para o produtor ' || P_USUARIO_ID || '.');
        WHEN E_CULTURA_NAO_CULTIVADA THEN
            RAISE_APPLICATION_ERROR(-20033, 'A cultura ' || V_CULTURA
                                    || ' não é cultivada na propriedade ' || P_PROPRIEDADE_ID || '.');
        WHEN E_DESCRICAO_INVALIDA THEN
            RAISE_APPLICATION_ERROR(-20034, 'A descrição deve ter de 10 a 1000 caracteres.');
        WHEN E_CHAVE_INVALIDA THEN
            RAISE_APPLICATION_ERROR(-20035, 'Chave de idempotência obrigatória, no formato UUID.');
        WHEN E_CHAVE_REUTILIZADA THEN
            RAISE_APPLICATION_ERROR(-20036, 'Chave de idempotência já usada com outro conteúdo.');
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20036, 'Chave de idempotência já usada com outro conteúdo.');
    END PRC_REGISTRAR_OCORRENCIA;

    PROCEDURE PRC_ATUALIZAR_STATUS (
        P_OCORRENCIA_ID IN OCORRENCIA.ID%TYPE,
        P_NOVO_STATUS   IN OCORRENCIA.STATUS%TYPE,
        P_SEVERIDADE    IN OCORRENCIA.SEVERIDADE%TYPE DEFAULT NULL
    )
    IS
        V_STATUS_ATUAL  OCORRENCIA.STATUS%TYPE;
        V_NOVO_STATUS   VARCHAR2(30) := UPPER(TRIM(P_NOVO_STATUS));
        V_QTD           NUMBER;

        E_OCORRENCIA_NAO_ENCONTRADA EXCEPTION;
        E_STATUS_INVALIDO           EXCEPTION;
        E_SEVERIDADE_OBRIGATORIA    EXCEPTION;
    BEGIN
        BEGIN
            SELECT STATUS INTO V_STATUS_ATUAL
              FROM OCORRENCIA
             WHERE ID = P_OCORRENCIA_ID
               FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE E_OCORRENCIA_NAO_ENCONTRADA;
        END;

        IF V_NOVO_STATUS IS NULL
           OR V_NOVO_STATUS NOT IN ('RECEBIDA', 'TRIADA', 'EM_ANALISE', 'CONFIRMADA', 'DESCARTADA') THEN
            RAISE E_STATUS_INVALIDO;
        END IF;

        IF NOT FN_TRANSICAO_PERMITIDA(V_STATUS_ATUAL, V_NOVO_STATUS) THEN
            RAISE E_TRANSICAO_INVALIDA;
        END IF;

        IF V_NOVO_STATUS = 'TRIADA' AND P_SEVERIDADE IS NULL THEN
            RAISE E_SEVERIDADE_OBRIGATORIA;
        END IF;

        UPDATE OCORRENCIA
           SET STATUS = V_NOVO_STATUS,
               SEVERIDADE = NVL(P_SEVERIDADE, SEVERIDADE),
               ATUALIZADO_EM = SYSTIMESTAMP
         WHERE ID = P_OCORRENCIA_ID;

        DBMS_OUTPUT.PUT_LINE('Ocorrência ' || P_OCORRENCIA_ID || ': ' || V_STATUS_ATUAL
                             || ' -> ' || V_NOVO_STATUS);

        IF V_NOVO_STATUS = 'TRIADA' THEN
            PKG_ALERTA.PRC_EMITIR_ALERTAS_RAIO(P_OCORRENCIA_ID, PKG_ALERTA.C_RAIO_PADRAO_KM, V_QTD);
        ELSIF V_NOVO_STATUS = 'CONFIRMADA' THEN
            PKG_ALERTA.PRC_ATUALIZAR_NIVEL(P_OCORRENCIA_ID, 'CONFIRMADO', V_QTD);
            PKG_ALERTA.PRC_EMITIR_ALERTAS_RAIO(P_OCORRENCIA_ID, PKG_ALERTA.C_RAIO_PADRAO_KM, V_QTD);
        ELSIF V_NOVO_STATUS = 'DESCARTADA' THEN
            PKG_ALERTA.PRC_ATUALIZAR_NIVEL(P_OCORRENCIA_ID, 'ENCERRADO', V_QTD);
        END IF;
    EXCEPTION
        WHEN E_OCORRENCIA_NAO_ENCONTRADA THEN
            RAISE_APPLICATION_ERROR(-20050, 'Ocorrência ' || P_OCORRENCIA_ID || ' não encontrada.');
        WHEN E_STATUS_INVALIDO THEN
            RAISE_APPLICATION_ERROR(-20051, 'Status inválido: ' || P_NOVO_STATUS || '.');
        WHEN E_TRANSICAO_INVALIDA THEN
            RAISE_APPLICATION_ERROR(-20052, 'Transição de ' || V_STATUS_ATUAL || ' para '
                                    || V_NOVO_STATUS || ' não permitida.');
        WHEN E_SEVERIDADE_OBRIGATORIA THEN
            RAISE_APPLICATION_ERROR(-20053, 'A triagem precisa informar a severidade, de 1 a 5.');
    END PRC_ATUALIZAR_STATUS;
END PKG_OCORRENCIA;
