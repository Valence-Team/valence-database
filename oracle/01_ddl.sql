SET SERVEROUTPUT ON
SET VERIFY OFF

-- Limpeza dos objetos do Valence
BEGIN
    FOR T IN (SELECT TABLE_NAME
                FROM USER_TABLES
               WHERE TABLE_NAME IN ('AUDITORIA_OCORRENCIA', 'POST_MURAL', 'LAUDO', 'ALERTA',
                                    'TRIAGEM', 'OCORRENCIA', 'PROPRIEDADE_CULTURA',
                                    'PROPRIEDADE', 'USUARIO')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || T.TABLE_NAME || ' CASCADE CONSTRAINTS PURGE';
        DBMS_OUTPUT.PUT_LINE('Tabela removida: ' || T.TABLE_NAME);
    END LOOP;

    FOR S IN (SELECT SEQUENCE_NAME
                FROM USER_SEQUENCES
               WHERE SEQUENCE_NAME IN ('SEQ_VALENCE_OCORRENCIA', 'SEQ_VALENCE_ALERTA',
                                       'SEQ_VALENCE_AUDITORIA')) LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || S.SEQUENCE_NAME;
        DBMS_OUTPUT.PUT_LINE('Sequência removida: ' || S.SEQUENCE_NAME);
    END LOOP;
END;
/

-- Tabelas DDL
CREATE TABLE USUARIO (
    ID          NUMBER(10)      CONSTRAINT PK_USUARIO PRIMARY KEY,
    NOME        VARCHAR2(100)   NOT NULL,
    EMAIL       VARCHAR2(150)   NOT NULL CONSTRAINT UK_USUARIO_EMAIL UNIQUE,
    SENHA_HASH  VARCHAR2(100)   NOT NULL,
    PAPEL       VARCHAR2(10)    NOT NULL,
    TELEFONE    VARCHAR2(20),
    MUNICIPIO   VARCHAR2(100)   NOT NULL,
    UF          CHAR(2)         NOT NULL,
    CRIADO_EM   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_USUARIO_PAPEL CHECK (PAPEL IN ('PRODUTOR', 'AGRONOMO', 'GESTOR')),
    CONSTRAINT CK_USUARIO_UF CHECK (UF IN ('AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO',
                                           'MA', 'MT', 'MS', 'MG', 'PA', 'PB', 'PR', 'PE', 'PI',
                                           'RJ', 'RN', 'RS', 'RO', 'RR', 'SC', 'SP', 'SE', 'TO'))
);

CREATE TABLE PROPRIEDADE (
    ID              NUMBER(10)      CONSTRAINT PK_PROPRIEDADE PRIMARY KEY,
    USUARIO_ID      NUMBER(10)      NOT NULL,
    NOME            VARCHAR2(100)   NOT NULL,
    MUNICIPIO       VARCHAR2(100)   NOT NULL,
    UF              CHAR(2)         NOT NULL,
    LATITUDE        NUMBER(9, 6)    NOT NULL,
    LONGITUDE       NUMBER(9, 6)    NOT NULL,
    AREA_HECTARES   NUMBER(10, 2)   NOT NULL,
    CRIADO_EM       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_PROPRIEDADE_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT CK_PROPRIEDADE_LATITUDE CHECK (LATITUDE BETWEEN -90 AND 90),
    CONSTRAINT CK_PROPRIEDADE_LONGITUDE CHECK (LONGITUDE BETWEEN -180 AND 180),
    CONSTRAINT CK_PROPRIEDADE_AREA CHECK (AREA_HECTARES > 0),
    CONSTRAINT CK_PROPRIEDADE_UF CHECK (UF IN ('AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO',
                                               'MA', 'MT', 'MS', 'MG', 'PA', 'PB', 'PR', 'PE', 'PI',
                                               'RJ', 'RN', 'RS', 'RO', 'RR', 'SC', 'SP', 'SE', 'TO'))
);

CREATE TABLE PROPRIEDADE_CULTURA (
    PROPRIEDADE_ID  NUMBER(10)      NOT NULL,
    CULTURA         VARCHAR2(10)    NOT NULL,
    CONSTRAINT PK_PROPRIEDADE_CULTURA PRIMARY KEY (PROPRIEDADE_ID, CULTURA),
    CONSTRAINT FK_PROP_CULTURA_PROPRIEDADE FOREIGN KEY (PROPRIEDADE_ID)
        REFERENCES PROPRIEDADE (ID) ON DELETE CASCADE,
    CONSTRAINT CK_PROP_CULTURA_CULTURA CHECK (CULTURA IN ('MILHO', 'TOMATE', 'BATATA'))
);

CREATE TABLE OCORRENCIA (
    ID              NUMBER(10)      CONSTRAINT PK_OCORRENCIA PRIMARY KEY,
    PROPRIEDADE_ID  NUMBER(10)      NOT NULL,
    USUARIO_ID      NUMBER(10)      NOT NULL,
    CULTURA         VARCHAR2(10)    NOT NULL,
    DESCRICAO       VARCHAR2(1000)  NOT NULL,
    STATUS          VARCHAR2(12)    DEFAULT 'RECEBIDA' NOT NULL,
    SEVERIDADE      NUMBER(1),
    IDEMPOTENCY_KEY VARCHAR2(36)    NOT NULL,
    DATA_REGISTRO   TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    ATUALIZADO_EM   TIMESTAMP,
    CONSTRAINT FK_OCORRENCIA_PROPRIEDADE FOREIGN KEY (PROPRIEDADE_ID) REFERENCES PROPRIEDADE (ID),
    CONSTRAINT FK_OCORRENCIA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT UK_OCORRENCIA_IDEMPOTENCIA UNIQUE (USUARIO_ID, IDEMPOTENCY_KEY),
    CONSTRAINT CK_OCORRENCIA_CULTURA CHECK (CULTURA IN ('MILHO', 'TOMATE', 'BATATA')),
    CONSTRAINT CK_OCORRENCIA_STATUS CHECK (STATUS IN ('RECEBIDA', 'TRIADA', 'EM_ANALISE',
                                                      'CONFIRMADA', 'DESCARTADA')),
    CONSTRAINT CK_OCORRENCIA_DESCRICAO CHECK (LENGTH(DESCRICAO) BETWEEN 10 AND 1000)
);

CREATE TABLE TRIAGEM (
    ID                  NUMBER(10)      CONSTRAINT PK_TRIAGEM PRIMARY KEY,
    OCORRENCIA_ID       NUMBER(10)      NOT NULL CONSTRAINT UK_TRIAGEM_OCORRENCIA UNIQUE,
    PRAGA_PROVAVEL      VARCHAR2(150),
    HIPOTESES           VARCHAR2(4000),
    CONFIANCA           NUMBER(5, 4),
    SEVERIDADE          NUMBER(1),
    CUIDADOS_IMEDIATOS  VARCHAR2(4000),
    TEXTO_ALERTA        VARCHAR2(500),
    ENCAMINHAR_AGRONOMO CHAR(1)         DEFAULT 'N' NOT NULL,
    EXPLICACAO          VARCHAR2(1500),
    FONTES              VARCHAR2(4000),
    MOTIVO_IMAGEM       VARCHAR2(40),
    GERADA_EM           TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_TRIAGEM_OCORRENCIA FOREIGN KEY (OCORRENCIA_ID)
        REFERENCES OCORRENCIA (ID) ON DELETE CASCADE,
    CONSTRAINT CK_TRIAGEM_HIPOTESES CHECK (HIPOTESES IS JSON),
    CONSTRAINT CK_TRIAGEM_CUIDADOS CHECK (CUIDADOS_IMEDIATOS IS JSON),
    CONSTRAINT CK_TRIAGEM_FONTES CHECK (FONTES IS JSON),
    CONSTRAINT CK_TRIAGEM_CONFIANCA CHECK (CONFIANCA BETWEEN 0 AND 1),
    CONSTRAINT CK_TRIAGEM_SEVERIDADE CHECK (SEVERIDADE BETWEEN 1 AND 5),
    CONSTRAINT CK_TRIAGEM_ENCAMINHAR CHECK (ENCAMINHAR_AGRONOMO IN ('S', 'N')),
    CONSTRAINT CK_TRIAGEM_MOTIVO CHECK (MOTIVO_IMAGEM IN ('RESOLUCAO_BAIXA', 'IMAGEM_ESCURA',
                                                         'IMAGEM_CLARA', 'IMAGEM_BORRADA',
                                                         'NAO_E_PLANTA', 'CULTURA_FORA_DO_ESCOPO',
                                                         'CULTURA_DIVERGENTE'))
);

CREATE TABLE ALERTA (
    ID              NUMBER(10)      CONSTRAINT PK_ALERTA PRIMARY KEY,
    OCORRENCIA_ID   NUMBER(10)      NOT NULL,
    PROPRIEDADE_ID  NUMBER(10)      NOT NULL,
    NIVEL           VARCHAR2(10)    DEFAULT 'SUSPEITA' NOT NULL,
    DISTANCIA_KM    NUMBER(5)       NOT NULL,
    LIDO            CHAR(1)         DEFAULT 'N' NOT NULL,
    CRIADO_EM       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ALERTA_OCORRENCIA FOREIGN KEY (OCORRENCIA_ID) REFERENCES OCORRENCIA (ID),
    CONSTRAINT FK_ALERTA_PROPRIEDADE FOREIGN KEY (PROPRIEDADE_ID) REFERENCES PROPRIEDADE (ID),
    CONSTRAINT UK_ALERTA_OCORRENCIA_PROP UNIQUE (OCORRENCIA_ID, PROPRIEDADE_ID),
    CONSTRAINT CK_ALERTA_NIVEL CHECK (NIVEL IN ('SUSPEITA', 'CONFIRMADO', 'ENCERRADO')),
    CONSTRAINT CK_ALERTA_DISTANCIA CHECK (DISTANCIA_KM >= 1),
    CONSTRAINT CK_ALERTA_LIDO CHECK (LIDO IN ('S', 'N'))
);

CREATE TABLE LAUDO (
    ID                  NUMBER(10)      CONSTRAINT PK_LAUDO PRIMARY KEY,
    OCORRENCIA_ID       NUMBER(10)      NOT NULL,
    AGRONOMO_ID         NUMBER(10)      NOT NULL,
    DECISAO             VARCHAR2(16)    NOT NULL,
    PRAGA_CONFIRMADA    VARCHAR2(150),
    PARECER             VARCHAR2(2000)  NOT NULL,
    EMITIDO_EM          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_LAUDO_OCORRENCIA FOREIGN KEY (OCORRENCIA_ID) REFERENCES OCORRENCIA (ID),
    CONSTRAINT FK_LAUDO_AGRONOMO FOREIGN KEY (AGRONOMO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT CK_LAUDO_DECISAO CHECK (DECISAO IN ('CONFIRMADA', 'DESCARTADA', 'MAIS_INFORMACOES')),
    CONSTRAINT CK_LAUDO_PARECER CHECK (LENGTH(PARECER) BETWEEN 20 AND 2000),
    CONSTRAINT CK_LAUDO_PRAGA CHECK (DECISAO <> 'CONFIRMADA' OR PRAGA_CONFIRMADA IS NOT NULL)
);

CREATE TABLE POST_MURAL (
    ID              NUMBER(10)      CONSTRAINT PK_POST_MURAL PRIMARY KEY,
    USUARIO_ID      NUMBER(10)      NOT NULL,
    OCORRENCIA_ID   NUMBER(10),
    MUNICIPIO       VARCHAR2(100)   NOT NULL,
    UF              CHAR(2)         NOT NULL,
    TEXTO           VARCHAR2(1000)  NOT NULL,
    STATUS          VARCHAR2(10)    DEFAULT 'ATIVO' NOT NULL,
    CRIADO_EM       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_POST_MURAL_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID),
    CONSTRAINT FK_POST_MURAL_OCORRENCIA FOREIGN KEY (OCORRENCIA_ID) REFERENCES OCORRENCIA (ID),
    CONSTRAINT CK_POST_MURAL_STATUS CHECK (STATUS IN ('ATIVO', 'OCULTO', 'REMOVIDO')),
    CONSTRAINT CK_POST_MURAL_TEXTO CHECK (LENGTH(TEXTO) BETWEEN 5 AND 1000)
);

CREATE TABLE AUDITORIA_OCORRENCIA (
    ID                  NUMBER(10)      CONSTRAINT PK_AUDITORIA_OCORRENCIA PRIMARY KEY,
    OCORRENCIA_ID       NUMBER(10)      NOT NULL,
    OPERACAO            VARCHAR2(6)     NOT NULL,
    STATUS_ANTERIOR     VARCHAR2(12),
    STATUS_NOVO         VARCHAR2(12),
    SEVERIDADE_ANTERIOR NUMBER(1),
    SEVERIDADE_NOVA     NUMBER(1),
    USUARIO_BANCO       VARCHAR2(128)   NOT NULL,
    DATA_OPERACAO       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT CK_AUDITORIA_OPERACAO CHECK (OPERACAO IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- Sequências
CREATE SEQUENCE SEQ_VALENCE_OCORRENCIA START WITH 1001 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VALENCE_ALERTA START WITH 1001 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_VALENCE_AUDITORIA START WITH 1 INCREMENT BY 1 NOCACHE;

