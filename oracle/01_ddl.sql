CREATE INDEX IX_LAUDO_OCORRENCIA ON LAUDO (OCORRENCIA_ID);
CREATE INDEX IX_AUDITORIA_OCORRENCIA ON AUDITORIA_OCORRENCIA (OCORRENCIA_ID);
