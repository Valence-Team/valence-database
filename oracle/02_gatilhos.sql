SET SERVEROUTPUT ON
SET VERIFY OFF

-- Gatilho de validação da severidade
CREATE OR REPLACE TRIGGER TRG_VALIDA_SEVERIDADE
BEFORE INSERT OR UPDATE OF SEVERIDADE, STATUS
ON OCORRENCIA
FOR EACH ROW
BEGIN
    IF :NEW.SEVERIDADE IS NOT NULL AND (:NEW.SEVERIDADE < 1 OR :NEW.SEVERIDADE > 5) THEN
        RAISE_APPLICATION_ERROR(-20001, 'Severidade inválida: ' || :NEW.SEVERIDADE
                                || '. O valor deve estar entre 1 e 5.');
    END IF;

    IF :NEW.STATUS = 'RECEBIDA' AND :NEW.SEVERIDADE IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20002, 'Ocorrência RECEBIDA não tem severidade. '
                                || 'A severidade é definida na triagem.');
    END IF;
END TRG_VALIDA_SEVERIDADE;
/

-- Gatilho de auditoria
CREATE OR REPLACE TRIGGER TRG_AUDIT_OCORRENCIA
AFTER INSERT OR DELETE OR UPDATE OF STATUS, SEVERIDADE
ON OCORRENCIA
FOR EACH ROW
DECLARE
    V_OPERACAO AUDITORIA_OCORRENCIA.OPERACAO%TYPE;
BEGIN
    IF INSERTING THEN
        V_OPERACAO := 'INSERT';
    ELSIF UPDATING THEN
        V_OPERACAO := 'UPDATE';
    ELSE
        V_OPERACAO := 'DELETE';
    END IF;

    INSERT INTO AUDITORIA_OCORRENCIA
        (ID, OCORRENCIA_ID, OPERACAO, STATUS_ANTERIOR, STATUS_NOVO,
         SEVERIDADE_ANTERIOR, SEVERIDADE_NOVA, USUARIO_BANCO, DATA_OPERACAO)
    VALUES
        (SEQ_VALENCE_AUDITORIA.NEXTVAL, NVL(:NEW.ID, :OLD.ID), V_OPERACAO, :OLD.STATUS, :NEW.STATUS,
         :OLD.SEVERIDADE, :NEW.SEVERIDADE, USER, SYSTIMESTAMP);
END TRG_AUDIT_OCORRENCIA;
/

SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
  FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('TRG_VALIDA_SEVERIDADE', 'TRG_AUDIT_OCORRENCIA');
